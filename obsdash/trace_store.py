"""
Phase 6: the trace backend -- a small, BOUNDED SQLite store of finished
spans, plus the exporter that feeds it.

Why SQLite and not Jaeger/Tempo (v1 decision): zero extra containers, the
dashboard API can query it directly, and it is plenty for a local
single-node tool. The trade-off is honest: it is not a scalable trace
backend. The OTLP exporter (Phase 3) can still ship the same spans to a
real backend through a Collector.

Bounded: at most `max_spans` rows are kept; when exceeded, the OLDEST
spans (by start time) are deleted. An observability tool that fills the
disk is worse than none.

Privacy: attribute keys that look like secrets are replaced by
"[redacted]", string values are truncated, and attribute count is
capped, so a careless instrumentation call cannot dump a credential or
a whole document into the database.

Thread-safety: the BatchSpanProcessor exports from a background thread
while API requests read from request threads; one connection, guarded by
a lock. The connection opens lazily, so merely importing/creating the app
never touches the disk.
"""

import json
import re
import sqlite3
import threading
import time
from typing import Sequence

from opentelemetry.sdk.trace import ReadableSpan
from opentelemetry.sdk.trace.export import SpanExporter, SpanExportResult

from obsdash.redaction import redact_text
from obsdash.span_redaction import sanitize_attributes  # noqa: F401  (re-exported)


# Traffic generated by looking at the dashboard must not fill the dashboard.
_SELF_TRAFFIC_PREFIXES = (
    "GET /metrics", "GET /api/traces", "GET /api/costs", "GET /api/overview",
    "GET /api/errors", "GET /api/alerts", "GET /dashboard", "GET unmatched /favicon",
    "GET /healthz",  # container liveness probe (Docker polls it every 15 s): not real traffic
    "POST /v1/traces",  # Phase 11: the act of receiving telemetry must not become telemetry
)
_MAX_STATUS_MESSAGE = 200

_SCHEMA = """
CREATE TABLE IF NOT EXISTS spans (
    trace_id   TEXT NOT NULL,
    span_id    TEXT NOT NULL,
    parent_id  TEXT,
    name       TEXT NOT NULL,
    kind       TEXT,
    service    TEXT,
    start_ns   INTEGER NOT NULL,
    end_ns     INTEGER NOT NULL,
    status     TEXT NOT NULL,
    attributes TEXT NOT NULL,
    status_message TEXT,
    PRIMARY KEY (trace_id, span_id)
);
CREATE INDEX IF NOT EXISTS idx_spans_start ON spans(start_ns);
"""


class QueryTimeout(Exception):
    """A store query ran past its time budget and was aborted."""


class _TimedLock:
    """A lock that also arms a per-operation deadline. While held, SQLite
    calls our progress handler every few thousand VM steps; once the
    deadline passes it aborts the statement (-> QueryTimeout), so one
    expensive query can never hold the store (and every request waiting on
    it) hostage."""

    def __init__(self, owner: "TraceStore") -> None:
        self._owner = owner
        self._lock = threading.Lock()

    def __enter__(self):
        self._lock.acquire()
        self._owner._deadline = time.monotonic() + self._owner._query_timeout_s
        return self

    def __exit__(self, exc_type, exc, tb):
        self._owner._deadline = None
        self._lock.release()
        if exc_type is sqlite3.OperationalError and "interrupted" in str(exc):
            raise QueryTimeout(f"store query exceeded {self._owner._query_timeout_s}s") from exc
        return False


class TraceStore:
    def __init__(self, path: str = "obsdash.db", max_spans: int = 50_000, retention_hours: int = 168,
                 query_timeout_s: float = 5.0, clock=time.time_ns) -> None:
        self._path = path
        self._max_spans = max_spans
        self._retention_ns = retention_hours * 3600 * 1_000_000_000
        self._query_timeout_s = query_timeout_s
        self._clock = clock
        self._deadline: float | None = None
        self._last_age_prune = 0.0
        self._lock = _TimedLock(self)
        self._conn: sqlite3.Connection | None = None

    def _progress(self) -> int:
        return 1 if self._deadline is not None and time.monotonic() > self._deadline else 0

    def _db(self) -> sqlite3.Connection:
        if self._conn is None:
            conn = sqlite3.connect(self._path, check_same_thread=False, timeout=5)
            conn.row_factory = sqlite3.Row
            if self._path != ":memory:":
                # WAL: readers (API) don't block the background writer and vice versa.
                conn.execute("PRAGMA journal_mode=WAL")
                conn.execute("PRAGMA synchronous=NORMAL")
            conn.set_progress_handler(self._progress, 1000)
            conn.executescript(_SCHEMA)
            # Migration: databases created by Phases 6-7 lack status_message.
            cols = {r["name"] for r in conn.execute("PRAGMA table_info(spans)")}
            if "status_message" not in cols:
                conn.execute("ALTER TABLE spans ADD COLUMN status_message TEXT")
            self._conn = conn
        return self._conn

    # ---- write ----
    @staticmethod
    def row_from_span(sp: ReadableSpan) -> tuple:
        ctx = sp.get_span_context()
        parent = sp.parent.span_id if sp.parent else None
        resource = sp.resource.attributes if sp.resource else {}
        return (
            format(ctx.trace_id, "032x"),
            format(ctx.span_id, "016x"),
            format(parent, "016x") if parent else None,
            redact_text(sp.name, 200),
            sp.kind.name,
            redact_text(str(resource.get("service.name", "unknown")), 100),
            sp.start_time or 0,
            sp.end_time or sp.start_time or 0,
            sp.status.status_code.name,
            json.dumps(sanitize_attributes(sp.attributes), default=str),
            redact_text(sp.status.description or "", _MAX_STATUS_MESSAGE) or None,
        )

    def add_spans(self, spans: Sequence[ReadableSpan]) -> None:
        self.add_rows([self.row_from_span(sp) for sp in spans if not sp.name.startswith(_SELF_TRAFFIC_PREFIXES)])

    def add_rows(self, rows: Sequence[tuple]) -> int:
        """Insert already-sanitized rows (same column order as `row_from_span`).
        Phase 11: the OTLP receiver builds rows from the wire format, not
        from SDK span objects. Self-traffic is filtered here too."""
        rows = [r for r in rows if not r[3].startswith(_SELF_TRAFFIC_PREFIXES)]
        if not rows:
            return 0
        with self._lock:
            db = self._db()
            db.executemany("INSERT OR REPLACE INTO spans (trace_id, span_id, parent_id, name, kind, service, "
                "start_ns, end_ns, status, attributes, status_message) VALUES (?,?,?,?,?,?,?,?,?,?,?)", rows)
            self._prune(db)
            db.commit()
        return len(rows)

    def _prune(self, db: sqlite3.Connection) -> None:
        # Age-based retention, at most once a minute (cheap on the write path).
        if time.monotonic() - self._last_age_prune >= 60:
            self._last_age_prune = time.monotonic()
            db.execute("DELETE FROM spans WHERE end_ns < ?", (self._clock() - self._retention_ns,))
        (count,) = db.execute("SELECT COUNT(*) FROM spans").fetchone()
        excess = count - self._max_spans
        if excess > 0:
            db.execute(
                "DELETE FROM spans WHERE rowid IN "
                "(SELECT rowid FROM spans ORDER BY start_ns ASC LIMIT ?)",
                (excess,),
            )

    # ---- read ----
    def span_count(self) -> int:
        with self._lock:
            return self._db().execute("SELECT COUNT(*) FROM spans").fetchone()[0]

    def list_traces(self, limit: int = 20, errors_only: bool = False) -> list[dict]:
        limit = max(1, min(int(limit), 100))
        having = "HAVING has_error = 1" if errors_only else ""
        with self._lock:
            db = self._db()
            rows = db.execute(
                f"""SELECT trace_id, MIN(start_ns) AS start_ns, MAX(end_ns) AS end_ns,
                           COUNT(*) AS span_count, MAX(status = 'ERROR') AS has_error
                    FROM spans GROUP BY trace_id {having}
                    ORDER BY start_ns DESC LIMIT ?""",
                (limit,),
            ).fetchall()
            out = []
            for r in rows:
                first = db.execute(
                    "SELECT name, service FROM spans WHERE trace_id = ? "
                    "ORDER BY (parent_id IS NOT NULL) ASC, start_ns ASC LIMIT 1",  # parentless span wins ties
                    (r["trace_id"],),
                ).fetchone()
                out.append({
                    "trace_id": r["trace_id"],
                    "root_name": first["name"],
                    "service": first["service"],
                    "start_ns": r["start_ns"],
                    "duration_ms": round((r["end_ns"] - r["start_ns"]) / 1e6, 3),
                    "span_count": r["span_count"],
                    "has_error": bool(r["has_error"]),
                })
            return out

    def query_spans(self, since_ns: int | None = None, kinds: tuple[str, ...] = ("SERVER", "CLIENT")) -> list[sqlite3.Row]:
        """Raw rows for analytics (obsdash/analytics.py). Bounded by the
        store's own span cap, so this never returns an unbounded set."""
        marks = ",".join("?" for _ in kinds)
        sql = f"SELECT * FROM spans WHERE kind IN ({marks})"
        params: list = list(kinds)
        if since_ns is not None:
            sql += " AND end_ns >= ?"
            params.append(since_ns)
        sql += " ORDER BY start_ns ASC"
        with self._lock:
            return self._db().execute(sql, params).fetchall()

    def bounds(self) -> dict:
        with self._lock:
            r = self._db().execute("SELECT COUNT(*) n, MIN(start_ns) lo, MAX(end_ns) hi FROM spans").fetchone()
        return {"spans_in_store": r["n"], "oldest_ns": r["lo"], "newest_ns": r["hi"]}

    def cost_summary(self, window_minutes: int | None = None) -> dict:
        """Aggregate model/embedding spans by (provider, model). Built only
        from spans still retained in the store (bounded), so it covers the
        retained window, not all-time spend."""
        where, params = "", []
        if window_minutes:
            where = "AND start_ns >= ?"
            params.append(time.time_ns() - int(window_minutes) * 60 * 1_000_000_000)

        def j(key: str) -> str:
            return f"json_extract(attributes, '$.\"{key}\"')"

        sql = f"""
            SELECT {j('gen_ai.system')} AS provider, {j('gen_ai.request.model')} AS model,
                   {j('obsdash.ai.cost_currency')} AS currency,
                   COUNT(*) AS calls,
                   SUM(CASE WHEN {j('obsdash.ai.cost_status')} = 'known' THEN 1 ELSE 0 END) AS priced,
                   SUM(CASE WHEN {j('obsdash.ai.cost_status')} IN ('unknown_model', 'no_usage') THEN 1 ELSE 0 END) AS unpriced,
                   SUM(COALESCE({j('gen_ai.usage.input_tokens')}, 0)) AS in_tok,
                   SUM(COALESCE({j('gen_ai.usage.output_tokens')}, 0)) AS out_tok,
                   SUM(COALESCE({j('obsdash.ai.cost_amount')}, 0)) AS cost
            FROM spans
            WHERE {j('gen_ai.operation.name')} IN ('model_call', 'embedding') {where}
            GROUP BY provider, model, currency"""
        with self._lock:
            rows = self._db().execute(sql, params).fetchall()

        merged: dict[tuple, dict] = {}
        for r in rows:
            m = merged.setdefault((r["provider"], r["model"]), {
                "provider": r["provider"], "model": r["model"], "calls": 0, "priced_calls": 0,
                "unpriced_calls": 0, "input_tokens": 0, "output_tokens": 0, "_costs": {},
            })
            m["calls"] += r["calls"]
            m["priced_calls"] += r["priced"]
            m["unpriced_calls"] += r["unpriced"]
            m["input_tokens"] += int(r["in_tok"])
            m["output_tokens"] += int(r["out_tok"])
            if r["currency"]:
                m["_costs"][r["currency"]] = m["_costs"].get(r["currency"], 0.0) + r["cost"]

        models, totals = [], {}
        for m in sorted(merged.values(), key=lambda x: (str(x["provider"]), str(x["model"]))):
            costs = m.pop("_costs")
            # Same definition as /api/overview: a call is "unpriced" only if it had a cost
            # status of unknown_model / no_usage. A FAILED call with no token usage is skipped for
            # cost (nothing was billed that we can see), so priced + unpriced can be < calls.
            m["cost_by_currency"] = {c: round(v, 6) for c, v in costs.items()}
            for c, v in costs.items():
                totals[c] = totals.get(c, 0.0) + v
            models.append(m)
        return {
            "models": models,
            "totals": {
                "calls": sum(m["calls"] for m in models),
                "unpriced_calls": sum(m["unpriced_calls"] for m in models),
                "cost_by_currency": {c: round(v, 6) for c, v in totals.items()},
            },
            "note": "Cost covers only calls with a known price; see unpriced_calls. "
                    "Based on spans still retained in the trace store.",
        }

    def get_trace(self, trace_id: str) -> dict | None:
        with self._lock:
            rows = self._db().execute(
                "SELECT * FROM spans WHERE trace_id = ? ORDER BY start_ns ASC", (trace_id,)
            ).fetchall()
        if not rows:
            return None
        nodes = {}
        for r in rows:
            nodes[r["span_id"]] = {
                "span_id": r["span_id"],
                "parent_id": r["parent_id"],
                "name": r["name"],
                "kind": r["kind"],
                "service": r["service"],
                "start_ns": r["start_ns"],
                "duration_ms": round((r["end_ns"] - r["start_ns"]) / 1e6, 3),
                "status": r["status"],
                "attributes": json.loads(r["attributes"]),
                "children": [],
            }
        roots = []
        for node in nodes.values():
            parent = nodes.get(node["parent_id"])
            # A span whose parent is not stored (remote caller, or pruned) is a root.
            (parent["children"] if parent else roots).append(node)
        return {
            "trace_id": trace_id,
            "span_count": len(nodes),
            "has_error": any(n["status"] == "ERROR" for n in nodes.values()),
            "roots": roots,
        }

    def close(self) -> None:
        with self._lock:
            if self._conn is not None:
                self._conn.close()
                self._conn = None


class TraceStoreExporter(SpanExporter):
    """Feeds finished spans into a TraceStore. Never raises into the app:
    a storage failure must not break the instrumented request."""

    def __init__(self, store: TraceStore, on_failure=None) -> None:
        self._store = store
        self._on_failure = on_failure

    def export(self, spans: Sequence[ReadableSpan]) -> SpanExportResult:
        try:
            self._store.add_spans(spans)
            return SpanExportResult.SUCCESS
        except Exception:  # noqa: BLE001 -- telemetry must fail soft
            if self._on_failure is not None:
                self._on_failure()
            return SpanExportResult.FAILURE

    def shutdown(self) -> None:
        pass
